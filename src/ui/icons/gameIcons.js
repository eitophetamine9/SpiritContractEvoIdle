/**
 * Returns SVG markup string for a requested game icon.
 * @param {string} iconKey
 * @param {Object} [options]
 * @param {string} [options.className]
 * @param {string|number} [options.size] - e.g. "16px", "20px" or 18
 * @param {string} [options.style]
 * @param {string} [options.color]
 * @param {boolean} [options.pulse]
 * @param {boolean} [options.glow]
 * @returns {string} SVG HTML string
 */
export function getGameIcon(iconKey, options = {}) {
  const svg = SVG_ICONS[iconKey] || SVG_ICONS['madness'];
  let size = options.size || '18px';
  if (typeof size === 'number') {
    size = `${size}px`;
  }
  const extraClasses = [
    'game-icon-wrap',
    options.className || '',
    options.pulse ? 'animated-icon-pulse' : '',
    options.glow ? 'animated-icon-glow' : '',
    options.float ? 'animated-icon-float' : '',
    options.spin ? 'animated-icon-spin' : ''
  ].filter(Boolean).join(' ');

  const styleColor = options.color ? `color: ${options.color};` : '';
  const extraStyle = options.style || '';

  return `<span class="${extraClasses}" style="display: inline-flex; align-items: center; justify-content: center; width: ${size}; height: ${size}; min-width: ${size}; min-height: ${size}; max-width: ${size}; max-height: ${size}; flex-shrink: 0; vertical-align: middle; line-height: 1; ${styleColor} ${extraStyle}">${svg}</span>`;
}

