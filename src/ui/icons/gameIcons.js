/**
 * Returns substat vector icon
 */
export function getSubstatIcon(subId, options = {}) {
  const id = String(subId || '').toLowerCase();
  if (id.includes('atk')) return getStatIcon('atk', options);
  if (id.includes('hp')) return getStatIcon('hp', options);
  if (id.includes('shield') || id.includes('def')) return getStatIcon('def', options);
  if (id.includes('crit_dmg')) return getGameIcon('zap', { color: '#ffa502', ...options });
  if (id.includes('crit')) return getStatIcon('crit', options);
  if (id.includes('mana')) return getStatIcon('mana', options);
  if (id.includes('ult')) return getGameIcon('sparkle', { color: '#c084fc', ...options });
  if (id.includes('evasion')) return getStatIcon('spd', options);
  if (id.includes('pierce')) return getGameIcon('swords', { color: '#ff4757', ...options });
  return getGameIcon('sparkle', options);
}
